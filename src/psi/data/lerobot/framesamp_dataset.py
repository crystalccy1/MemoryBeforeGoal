from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

import torch
from safetensors import safe_open

from psi.data.lerobot.framesamp_features import (
    FEATURE_BANK_SCHEMA_VERSION,
    FEATURE_CONTRACT_SCHEMA_VERSION,
    assemble_memory_tokens,
    memory_raw_frame_indices,
    raw_frame_indices,
    sha256_file,
)


@lru_cache(maxsize=16)
def _verify_shards_once(
    manifest_path_value: str, manifest_sha256: str
) -> dict[int, tuple[int, int, int]]:
    """Hash the complete bank once per rank, before DataLoader workers fork."""

    manifest_path = Path(manifest_path_value).resolve(strict=True)
    if sha256_file(manifest_path) != manifest_sha256:
        raise RuntimeError("FrameSamp manifest changed before shard verification")
    manifest = json.loads(manifest_path.read_text())
    verified: dict[int, tuple[int, int, int]] = {}
    for record in manifest.get("outputs") or []:
        path = Path(record["path"])
        if (
            path.is_symlink()
            or not path.is_file()
            or path.stat().st_size != record["bytes"]
            or sha256_file(path) != record["sha256"]
        ):
            raise RuntimeError(f"FrameSamp shard identity mismatch: {path}")
        stat = path.stat()
        verified[int(record["episode_index"])] = (
            int(stat.st_size),
            int(stat.st_mtime_ns),
            int(stat.st_ino),
        )
    return verified


class FrameSampFeatureBank:
    """Fail-closed reader and fixed-budget assembler for a FrameSamp bank."""

    def __init__(
        self,
        root: str | Path,
        *,
        expected_task: str,
        expected_dataset_revision: str,
        expected_scope: str,
        expected_manifest_sha256: str,
        expected_frame_stride: int = 1,
        expected_max_memory_frames: int = 32,
        expected_tokens_per_frame: int = 16,
        expected_feature_dim: int = 2048,
        expected_online_memory_view: str = "rgb_head_stereo_left",
    ) -> None:
        self.root = Path(root).resolve(strict=True)
        contract_path = self.root / "contract.json"
        manifest_path = self.root / "manifest.json"
        ready_path = self.root / "READY"
        for path in (contract_path, manifest_path, ready_path):
            if path.is_symlink() or not path.is_file():
                raise RuntimeError(f"Missing or unsafe FrameSamp bank file: {path}")
        self.contract = json.loads(contract_path.read_text())
        self.manifest = json.loads(manifest_path.read_text())
        ready = json.loads(ready_path.read_text())
        if self.contract.get("schema_version") != FEATURE_CONTRACT_SCHEMA_VERSION:
            raise RuntimeError("FrameSamp contract schema mismatch")
        if self.manifest.get("schema_version") != FEATURE_BANK_SCHEMA_VERSION:
            raise RuntimeError("FrameSamp manifest schema mismatch")
        if ready.get("schema_version") != FEATURE_BANK_SCHEMA_VERSION:
            raise RuntimeError("FrameSamp READY schema mismatch")
        manifest_sha256 = sha256_file(manifest_path)
        if manifest_sha256 != expected_manifest_sha256:
            raise RuntimeError("FrameSamp manifest is not the pinned training input")
        if ready.get("manifest_sha256") != manifest_sha256:
            raise RuntimeError("FrameSamp READY does not bind its manifest")
        if (
            self.contract.get("task") != expected_task
            or self.manifest.get("task") != expected_task
            or ready.get("task") != expected_task
            or self.contract.get("scope") != expected_scope
            or self.manifest.get("scope") != expected_scope
            or ready.get("scope") != expected_scope
            or self.contract["dataset"].get("revision")
            != expected_dataset_revision
        ):
            raise RuntimeError("FrameSamp bank task/scope/dataset revision mismatch")
        if self.manifest.get("contract_sha256") != sha256_file(contract_path):
            raise RuntimeError("FrameSamp manifest does not bind its contract")
        from psi.models.framesamp_qwen import (
            QwenVisionMergerFrameProducer,
            qwen_frame_producer_source_path,
        )

        producer_path = qwen_frame_producer_source_path()
        producer_record = self.contract.get("code_files", {}).get(
            "shared_offline_online_producer", {}
        )
        if (
            producer_record.get("bytes") != producer_path.stat().st_size
            or producer_record.get("sha256") != sha256_file(producer_path)
        ):
            raise RuntimeError(
                "FrameSamp bank was generated by a different Qwen producer source"
            )
        if (
            self.manifest.get("status") != "complete"
            or ready.get("manifest") != "manifest.json"
            or self.manifest.get("episodes") != ready.get("episodes")
            or self.manifest.get("raw_frames") != ready.get("raw_frames")
            or self.manifest.get("raw_frames")
            != self.contract.get("dataset", {}).get("selected_frames")
            or self.manifest.get("feature_shape_tail") != [16, 2048]
        ):
            raise RuntimeError("FrameSamp bank is not a complete compatible release")

        clock = self.contract["memory_clock"]
        preprocess = self.contract["preprocess"]
        encoder = self.contract["encoder"]
        if (
            clock.get("type") != "raw_execution_frame"
            or clock.get("visible_prefix") != "episode_start_through_current_inclusive"
            or clock.get("selection") != "dynamic_uniform_integer_linspace"
            or clock.get("padding_side") != "right"
            or clock.get("anchor_origin_raw_frame") != 0
            or clock.get("include_current_frame") is not True
            or clock.get("training_rows_are_not_filtered") is not True
            or clock.get("current_observation_is_separate_system2_input") is not True
            or clock.get("raw_frame_stride") != expected_frame_stride
            or clock.get("max_memory_frames") != expected_max_memory_frames
            or not isinstance(clock.get("offline_image_key"), str)
            or not clock.get("offline_image_key")
            or clock.get("online_image_key") != expected_online_memory_view
            or preprocess.get("tokens_per_frame") != expected_tokens_per_frame
            or preprocess.get("producer_schema_version")
            != QwenVisionMergerFrameProducer.SCHEMA_VERSION
            or encoder.get("feature_dim") != expected_feature_dim
            or encoder.get("dtype") != "bfloat16"
            or encoder.get("batching_policy") != "canonical_singleton_per_frame"
            or encoder.get("attention_backend") != "sdpa"
            or preprocess.get("spatial_pool") != "adaptive_mean_2d"
        ):
            raise RuntimeError("Unsupported strict FrameSamp v2 assembly contract")
        self.frame_stride = int(clock["raw_frame_stride"])
        self.max_memory_frames = int(clock["max_memory_frames"])
        self.tokens_per_frame = int(preprocess["tokens_per_frame"])
        self.feature_dim = int(encoder["feature_dim"])
        self.memory_budget = self.max_memory_frames * self.tokens_per_frame
        self.contract_sha256 = sha256_file(contract_path)

        outputs = self.manifest.get("outputs") or []
        self._outputs = {int(item["episode_index"]): item for item in outputs}
        expected_episodes = self.contract["dataset"].get("selected_episode_indices")
        if (
            len(self._outputs) != len(outputs)
            or len(outputs) != self.manifest.get("episodes")
            or sorted(self._outputs) != expected_episodes
            or sum(int(item.get("source_frames", -1)) for item in outputs)
            != self.manifest.get("raw_frames")
        ):
            raise RuntimeError("FrameSamp manifest episode set is incomplete or duplicated")
        self._verified_shards = _verify_shards_once(
            str(manifest_path), manifest_sha256
        )
        if set(self._verified_shards) != set(self._outputs):
            raise RuntimeError("FrameSamp shard verification did not cover every episode")

    @lru_cache(maxsize=8)
    def _load_episode(self, episode_index: int) -> tuple[torch.Tensor, torch.Tensor]:
        # Safetensors tensors are memory-mapped. Keep several recent mappings;
        # only selected 32-frame pages are copied into each training sample.
        record = self._outputs.get(int(episode_index))
        if record is None:
            raise KeyError(f"Episode {episode_index} is absent from FrameSamp bank")
        recorded_path = Path(record["path"])
        if recorded_path.is_symlink():
            raise RuntimeError(f"FrameSamp shard must not be a symlink: {recorded_path}")
        path = recorded_path.resolve(strict=True)
        try:
            path.relative_to((self.root / "episodes").resolve(strict=True))
        except ValueError as exc:
            raise RuntimeError(f"FrameSamp shard escapes bank root: {path}") from exc
        stat = path.stat()
        observed_identity = (int(stat.st_size), int(stat.st_mtime_ns), int(stat.st_ino))
        if observed_identity != self._verified_shards[int(episode_index)]:
            raise RuntimeError(f"FrameSamp shard identity mismatch: {path}")
        with safe_open(path, framework="pt", device="cpu") as handle:
            metadata = handle.metadata() or {}
            features = handle.get_tensor("features")
            raw_indices = handle.get_tensor("raw_frame_indices")
            source_grid_hw = handle.get_tensor("source_grid_hw")
        expected_metadata = {
            "schema_version": FEATURE_BANK_SCHEMA_VERSION,
            "task": self.contract["task"],
            "episode_index": str(episode_index),
            "raw_frame_stride": str(self.frame_stride),
            "contract_sha256": self.contract_sha256,
        }
        if metadata != expected_metadata:
            raise RuntimeError(f"FrameSamp shard metadata mismatch: {path}")
        if (
            tuple(features.shape)
            != (int(record["source_frames"]), self.tokens_per_frame, self.feature_dim)
            or features.dtype != torch.bfloat16
            or raw_indices.shape != (int(record["source_frames"]),)
            or raw_indices.dtype != torch.int64
            or source_grid_hw.shape != (int(record["source_frames"]), 2)
            or source_grid_hw.dtype != torch.int64
        ):
            raise RuntimeError(f"FrameSamp shard tensor contract mismatch: {path}")
        expected_raw = torch.from_numpy(raw_frame_indices(int(record["source_frames"])))
        if (
            not torch.equal(raw_indices, expected_raw)
            or not torch.all(source_grid_hw > 0)
        ):
            raise RuntimeError(f"FrameSamp shard violates the frozen clock/grid: {path}")
        return features, raw_indices

    def memory_for_frame(
        self, episode_index: int, current_frame_index: int
    ) -> dict[str, torch.Tensor]:
        record = self._outputs.get(int(episode_index))
        if record is None:
            raise KeyError(f"Episode {episode_index} is absent from FrameSamp bank")
        selected_raw = memory_raw_frame_indices(
            int(current_frame_index),
            int(record["source_frames"]),
            self.max_memory_frames,
        )
        features, bank_raw = self._load_episode(int(episode_index))
        selected_positions = torch.from_numpy(selected_raw)
        selected_bank_raw = bank_raw.index_select(0, selected_positions)
        if not torch.equal(selected_bank_raw, torch.from_numpy(selected_raw)):
            raise RuntimeError("FrameSamp bank indices do not match the raw-frame clock")
        selected_features = features.index_select(0, selected_positions)
        memory = assemble_memory_tokens(
            selected_features,
            selected_bank_raw,
            max_memory_frames=self.max_memory_frames,
            tokens_per_frame=self.tokens_per_frame,
            feature_dim=self.feature_dim,
        )
        return {
            **memory,
            "selected_raw_frame_indices": selected_bank_raw.clone(),
        }
